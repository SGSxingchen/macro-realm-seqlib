def _key(name: str) -> str:
    return unicodedata.normalize("NFKC", name).strip().casefold()


_CANONICAL_NAMES = {
    _key(name): canonical
    for canonical, aliases in AUTHOR_ALIASES.items()
    for name in (canonical, *aliases)
}


def canonical_author(name: str) -> str:
    """已登记别名归一；未登记姓名不作修改。"""
    return _CANONICAL_NAMES.get(_key(name), name.strip())


def is_known_author(name: str) -> bool:
    """用于分隔多人署名前先保留词典中已登记的完整复合姓名。"""
    return _key(name) in _CANONICAL_NAMES
